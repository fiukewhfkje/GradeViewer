import Link from "http-link-header";
import { ApiError } from "./provider";
import type { CookieJar } from "tough-cookie";
export const canvasOrigin = "https://osu.instructure.com";
export const canvasCoursesPath =
  "/api/v1/courses?enrollment_type=student&include[]=total_scores&include[]=term&include[]=teachers&per_page=100";
export function canvasSessionHeaders(jar: CookieJar, url: URL) {
  if (!canvasAllowed(url)) throw new ApiError(400, "invalidRequest");
  const headers = new Headers({
    Accept: "application/json",
    Cookie: jar.getCookieStringSync(url.href),
    "User-Agent": "GradeViewer/0.2 (read-only student session)",
    "X-Requested-With": "XMLHttpRequest",
    Referer: canvasOrigin + "/",
  });
  const csrf = jar
    .getCookiesSync(url.href)
    .find((c) => c.key === "_csrf_token");
  if (csrf) {
    let token: string;
    try {
      token = decodeURIComponent(csrf.value);
    } catch {
      throw new ApiError(502, "malformedCanvas");
    }
    if (!token || token.length > 10000 || /[^\x20-\x7e]/.test(token))
      throw new ApiError(502, "malformedCanvas");
    headers.set("X-CSRF-Token", token);
  }
  return headers;
}
export async function canvasRejection(response: Response) {
  const contentType = response.headers.get("Content-Type") ?? "",
    responseType = contentType.includes("application/json")
      ? "json"
      : contentType.includes("text/html")
        ? "html"
        : "other";
  if (response.headers.get("cf-mitigated") === "challenge") {
    await response.body?.cancel();
    return { responseType, reason: "challenge" } as const;
  }
  // Inspect a bounded error only in memory. Persist fixed enums, never the body.
  const reader = response.body?.getReader(),
    decoder = new TextDecoder();
  let text = "",
    size = 0;
  try {
    while (reader && size < 8192) {
      const { done, value } = await reader.read();
      if (done) break;
      text += decoder.decode(value.subarray(0, 8192 - size), { stream: true });
      size += value.length;
    }
  } catch {
    /* An unreadable rejection remains unknown, never an invented permission error. */
  } finally {
    await reader?.cancel().catch(() => {});
  }
  const reason =
    /invalid authenticity token|invalid csrf token|csrf token missing/i.test(
      text,
    )
      ? "csrf"
      : /challenge-platform|awswaf|generated by cloudfront|request blocked/i.test(
            text,
          )
        ? "challenge"
        : /user not authorized to perform that action/i.test(text)
          ? "permission"
          : /user authorization required/i.test(text)
            ? "authentication"
            : "unknown";
  return { responseType, reason };
}
export function canvasURL(input: unknown = canvasOrigin) {
  if (input !== canvasOrigin && input !== canvasOrigin + "/")
    throw new ApiError(400, "invalidRequest");
  return new URL(canvasOrigin);
}
export function canvasAllowed(u: URL) {
  if (
    u.origin !== canvasOrigin ||
    u.username ||
    u.password ||
    u.hash ||
    u.href.length > 2000
  )
    return false;
  if (
    !/^\/api\/v1\/(users\/self\/profile|courses(?:\/[1-9]\d{0,19}\/(assignment_groups|enrollments))?)$/.test(
      u.pathname,
    )
  )
    return false;
  const allowed = new Set([
    "enrollment_type",
    "include[]",
    "per_page",
    "page",
    "user_id",
    "type[]",
  ]);
  return (
    [...u.searchParams.keys()].every((k) => allowed.has(k)) &&
    (!u.searchParams.has("per_page") ||
      /^[1-9]\d{0,2}$/.test(u.searchParams.get("per_page")!)) &&
    (!u.searchParams.has("page") ||
      /^[a-zA-Z0-9_=-]{1,100}$/.test(u.searchParams.get("page")!))
  );
}
export function canvasNext(link: string | null, current: URL, first: URL) {
  if (!link) return;
  if (link.length > 12000) throw new ApiError(502, "malformedCanvas");
  const next = Link.parse(link).rel("next");
  if (!next.length) return;
  if (next.length !== 1) throw new ApiError(502, "malformedCanvas");
  const u = new URL(next[0].uri, current);
  const scope = (url: URL) =>
    [...url.searchParams]
      .filter(([k]) => !["page", "per_page"].includes(k))
      .map((x) => JSON.stringify(x))
      .sort()
      .join(";");
  if (
    !canvasAllowed(u) ||
    u.pathname !== first.pathname ||
    scope(u) !== scope(first)
  )
    throw new ApiError(502, "invalidPortalRedirect");
  return u;
}
